def load_groups(cases_dir):
    cases_dir = Path(cases_dir)
    if not cases_dir.is_dir():
        raise SystemExit("cases directory not found: %s" % cases_dir)
    groups = []
    for path in sorted(cases_dir.glob("*.json")):
        with path.open(encoding="utf-8") as fh:
            data = json.load(fh)
        name = data.get("group") or path.stem
        cases = data.get("cases") or []
        seen = set()
        for case in cases:
            if case["name"] in seen:
                raise SystemExit("duplicate case name %r in %s"
                                 % (case["name"], path))
            seen.add(case["name"])
        groups.append({"group": name,
                       "description": data.get("description", ""),
                       "path": path,
                       "cases": cases})
    if not groups:
        raise SystemExit("no *.json case files under %s" % cases_dir)
    return groups


