class CaseRunner:
    def __init__(self, server, timeout, verbose):
        self.server = server
        self.timeout = timeout
        self.verbose = verbose
        self.control = None

    # -- control connection ------------------------------------------------

    def _control(self):
        if self.control is None:
            self.control = Client(self.server.host, self.server.port,
                                  self.timeout)
        return self.control

    def drop_control(self):
        if self.control is not None:
            self.control.close()
            self.control = None

    def reset(self):
        """Wipe every database. Raises ServerGone if the server is unusable."""
        for attempt in range(2):
            try:
                ctl = self._control()
                payload = bytearray()
                for db in range(16):
                    payload += enc_cmd(["SELECT", str(db)])
                    payload += enc_cmd(["FLUSHDB"])
                payload += enc_cmd(["SELECT", "0"])
                ctl.send(bytes(payload))
                for _ in range(33):
                    reply = ctl.read_reply(self.timeout)
                    if reply != ("+", "OK"):
                        raise ServerGone(
                            "per-case reset failed: SELECT/FLUSHDB answered %s"
                            % describe(reply))
                return
            except (CaseFailure, OSError) as exc:
                self.drop_control()
                if attempt == 1:
                    raise ServerGone("per-case reset failed: %s" % exc)

    # -- one case ----------------------------------------------------------

    def run_case(self, case):
        clients = {}

        def client_for(name):
            if name not in clients:
                clients[name] = Client(self.server.host, self.server.port,
                                       self.timeout)
            return clients[name]

        try:
            for index, step in enumerate(case.get("steps", []), start=1):
                label = step_label(step)
                if self.verbose:
                    print("      step %-3d %s" % (index, label))
                try:
                    self.run_step(step, client_for)
                except CaseFailure as exc:
                    detail = ["step %d: %s" % (index, label)]
                    for line in str(exc.message).splitlines():
                        detail.append("      %s" % line)
                    detail.extend(exc.detail)
                    raise CaseFailure("step %d failed" % index, detail)
                except OSError as exc:
                    raise CaseFailure(
                        "step %d failed" % index,
                        ["step %d: %s" % (index, label),
                         "      socket error: %s" % exc])
        finally:
            for c in clients.values():
                c.close()

    def run_step(self, step, client_for):
        name = step.get("client", "c1")

        if "note" in step and len(step) == 1:
            return
        if "sleep_ms" in step:
            time.sleep(step["sleep_ms"] / 1000.0)
            return
        if step.get("connect"):
            client_for(name)
            return
        if step.get("close"):
            client_for(name).close()
            return

        client = client_for(name)

        if "scan_collect" in step:
            self.run_scan_collect(step, client)
            return

        if "cmd" in step:
            client.send(enc_cmd([str(a) for a in step["cmd"]]))
        elif "send" in step:
            client.send(step["send"].encode("latin-1"))

        if "expect_closed" in step:
            client.expect_closed(self.timeout)
            return
        if "expect_nothing_ms" in step:
            client.expect_nothing(step["expect_nothing_ms"])
            return
        if "expect" in step:
            reply = client.read_reply(self.timeout)
            why = match(step["expect"], reply)
            if why is not None:
                raise CaseFailure(why)
            return
        if "expect_repeat" in step:
            # repeat: [count, expectation] -- read the same reply N times
            count, exp = step["expect_repeat"]
            for i in range(count):
                reply = client.read_reply(self.timeout)
                why = match(exp, reply)
                if why is not None:
                    raise CaseFailure("repetition %d: %s" % (i + 1, why))
            return
        if not ("cmd" in step or "send" in step):
            raise CaseFailure("step has no recognised action: %r" % (step,))

    def run_scan_collect(self, step, client):
        opts = step["scan_collect"]
        match_pat = opts.get("match")
        count = opts.get("count")
        max_calls = opts.get("max_calls", 200)
        cursor = "0"
        seen = []
        calls = 0
        while True:
            args = ["SCAN", cursor]
            if match_pat is not None:
                args += ["MATCH", match_pat]
            if count is not None:
                args += ["COUNT", str(count)]
            client.send(enc_cmd(args))
            reply = client.read_reply(self.timeout)
            calls += 1
            kind, value = reply
            if kind != "*" or value is None or len(value) != 2:
                raise CaseFailure(
                    "SCAN %s must reply a 2-element array, got %s"
                    % (cursor, describe(reply)))
            cur_kind, cur_val = value[0]
            if cur_kind != "$" or cur_val is None:
                raise CaseFailure(
                    "SCAN cursor element must be a bulk string, got %s"
                    % describe(value[0]))
            if not cur_val.isdigit() or (len(cur_val) > 1
                                         and cur_val.startswith("0")):
                raise CaseFailure(
                    "SCAN cursor %r is not an unsigned decimal without "
                    "leading zeros" % cur_val)
            if int(cur_val) > 18446744073709551615:
                raise CaseFailure("SCAN cursor %r exceeds 64 bits" % cur_val)
            keys_kind, keys_val = value[1]
            if keys_kind != "*" or keys_val is None:
                raise CaseFailure(
                    "SCAN key element must be an array, got %s"
                    % describe(value[1]))
            for element in keys_val:
                if element[0] != "$" or element[1] is None:
                    raise CaseFailure(
                        "SCAN returned a non-bulk key: %s" % describe(element))
                seen.append(element[1])
            cursor = cur_val
            if cursor == "0":
                break
            if calls >= max_calls:
                raise CaseFailure(
                    "SCAN did not finish within %d call(s); a full iteration "
                    "must terminate (SPEC.md 7.4)" % max_calls)
        expected = set(step["expect_keys"])
        got = set(seen)
        if got != expected:
            missing = sorted(expected - got)
            extra = sorted(got - expected)
            raise CaseFailure(
                "full SCAN iteration returned the wrong key set after %d "
                "call(s)\n        missing: %r\n        unexpected: %r"
                % (calls, missing[:12], extra[:12]))


def step_label(step):
    if "cmd" in step:
        text = " ".join(str(a) for a in step["cmd"])
    elif "send" in step:
        text = "send %r" % step["send"]
    elif "scan_collect" in step:
        text = "scan_collect %r" % (step["scan_collect"],)
    elif "sleep_ms" in step:
        text = "sleep %d ms" % step["sleep_ms"]
    elif step.get("connect"):
        text = "connect"
    elif step.get("close"):
        text = "close"
    elif "expect_closed" in step:
        text = "expect connection closed"
    elif "expect_nothing_ms" in step:
        text = "expect silence for %d ms" % step["expect_nothing_ms"]
    elif "expect" in step:
        text = "read reply"
    else:
        text = "(no action)"
    if len(text) > 96:
        text = text[:93] + "..."
    who = step.get("client", "c1")
    return "[%s] %s" % (who, text)


