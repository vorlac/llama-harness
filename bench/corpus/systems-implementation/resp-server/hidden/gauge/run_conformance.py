def main(argv=None):
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-sh", help="path to the workspace run.sh")
    ap.add_argument("--cases-dir", default=str(DEFAULT_CASES),
                    help="directory of *.json case files")
    ap.add_argument("--group", action="append", default=[],
                    help="run only this group; repeatable")
    ap.add_argument("--case", action="append", default=[],
                    help="run only cases whose name contains this substring")
    ap.add_argument("--list-groups", action="store_true")
    ap.add_argument("--port", type=int, default=0,
                    help="port to hand the server (default: a free one)")
    ap.add_argument("--timeout", type=float, default=5.0,
                    help="per-read socket timeout in seconds")
    ap.add_argument("--fail-fast", action="store_true")
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument("--json", dest="json_path",
                    help="write a machine-readable report here")
    args = ap.parse_args(argv)

    groups = load_groups(args.cases_dir)

    if args.list_groups:
        total = 0
        for g in groups:
            print("%-16s %4d case(s)   %s"
                  % (g["group"], len(g["cases"]), g["description"]))
            total += len(g["cases"])
        print("%-16s %4d case(s)" % ("TOTAL", total))
        return 0

    if not args.run_sh:
        ap.error("--run-sh is required unless --list-groups is given")

    wanted = set(args.group)
    if wanted:
        unknown = wanted - {g["group"] for g in groups}
        if unknown:
            raise SystemExit("unknown group(s): %s" % ", ".join(sorted(unknown)))
        groups = [g for g in groups if g["group"] in wanted]

    if args.case:
        for g in groups:
            g["cases"] = [c for c in g["cases"]
                          if any(s in c["name"] for s in args.case)]
        groups = [g for g in groups if g["cases"]]
        if not groups:
            raise SystemExit("no cases matched --case")

    port = args.port or free_port()
    server = Server(args.run_sh, port)
    server.start()
    try:
        server.wait_ready()
    except ServerGone as exc:
        server.stop()
        print("SERVER NOT READY: %s" % exc, file=sys.stderr)
        print("conformance: 0/%d passed (0.0%%) in %d group(s)"
              % (sum(len(g["cases"]) for g in groups), len(groups)))
        return 1

    runner = CaseRunner(server, args.timeout, args.verbose)
    results = []
    passed = failed = 0
    stopped_early = False
    started = time.monotonic()

    try:
        for g in groups:
            if stopped_early:
                break
            for case in g["cases"]:
                title = "[%s] %s " % (g["group"], case["name"])
                dots = "." * max(3, NAME_WIDTH - len(title))
                reason = None
                detail = []
                try:
                    runner.reset()
                    runner.run_case(case)
                except CaseFailure as exc:
                    reason = exc.message
                    detail = exc.detail
                except ServerGone as exc:
                    reason = "server exited"
                    detail = ["      %s" % line
                              for line in str(exc).splitlines()]
                    runner.drop_control()
                    if server.restarts >= MAX_RESTARTS:
                        stopped_early = True
                    else:
                        try:
                            server.restart()
                        except ServerGone as exc2:
                            detail.append("      restart failed: %s" % exc2)
                            stopped_early = True
                except Exception as exc:      # noqa: BLE001 - runner robustness
                    reason = "runner error: %s: %s" % (type(exc).__name__, exc)
                    detail = []
                    runner.drop_control()
                    if not server.alive():
                        if server.restarts >= MAX_RESTARTS:
                            stopped_early = True
                        else:
                            try:
                                server.restart()
                            except ServerGone as exc2:
                                detail.append("      restart failed: %s" % exc2)
                                stopped_early = True

                if reason is None:
                    passed += 1
                    print("%s%s PASS" % (title, dots))
                else:
                    failed += 1
                    print("%s%s FAIL" % (title, dots))
                    print("    %s" % reason)
                    for line in detail:
                        print("    %s" % line)
                results.append({"group": g["group"], "name": case["name"],
                                "passed": reason is None, "reason": reason,
                                "detail": detail})
                if reason is not None and args.fail_fast:
                    stopped_early = True
                if stopped_early:
                    # --fail-fast, or the restart budget is gone (SPEC.md 12.5):
                    # stop now and count the rest as not run.
                    break
    finally:
        server.stop()

    remaining = sum(len(g["cases"]) for g in groups) - (passed + failed)
    if remaining > 0:
        failed += remaining
        print("    %d case(s) not run (the run stopped early)" % remaining)

    total = passed + failed
    pct = (100.0 * passed / total) if total else 0.0
    elapsed = time.monotonic() - started
    if server.restarts:
        print("server restarts: %d" % server.restarts)
    print("elapsed: %.1fs" % elapsed)
    print("conformance: %d/%d passed (%.1f%%) in %d group(s)"
          % (passed, total, pct, len(groups)))

    if args.json_path:
        with open(args.json_path, "w", encoding="utf-8") as fh:
            json.dump({"passed": passed, "total": total, "pct": round(pct, 2),
                       "groups": [g["group"] for g in groups],
                       "restarts": server.restarts,
                       "elapsed_seconds": round(elapsed, 3),
                       "results": results}, fh, indent=2)
            fh.write("\n")

    return 0 if failed == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
