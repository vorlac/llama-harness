#!/usr/bin/env python3
"""Conformance runner for the `resp-server` task.

Language-neutral by construction: the cases are JSON data under cases/, the
server under test is any program that satisfies the harness contract in
SPEC.md section 2, and this runner is the only executable piece. It starts the
server through run.sh, drives real TCP sockets against it, and compares real
bytes.

    python3 run_conformance.py --run-sh ./run.sh
    python3 run_conformance.py --run-sh ./run.sh --group protocol --verbose
    python3 run_conformance.py --run-sh ./run.sh --list-groups

Exit status is 0 if and only if every selected case passed.

Python 3.8+, standard library only. Do not edit this file: the scorer runs its
own pristine copy, so local edits change nothing except your own numbers.
"""

from __future__ import annotations

