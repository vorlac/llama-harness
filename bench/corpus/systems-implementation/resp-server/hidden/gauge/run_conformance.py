from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_CASES = HERE / "cases"

READY_TIMEOUT = 20.0          # seconds to wait for the server to accept
SHUTDOWN_GRACE = 5.0          # seconds between SIGTERM and SIGKILL
MAX_RESTARTS = 10             # server restarts tolerated per run
NAME_WIDTH = 58               # case-name column width in the report


# --------------------------------------------------------------------------
# failures
# --------------------------------------------------------------------------

class CaseFailure(Exception):
    """A case did not conform. Carries a human-readable, multi-line reason."""

    def __init__(self, message, detail=None):
        super().__init__(message)
        self.message = message
        self.detail = detail or []


class ServerGone(Exception):
    """The server process died or became unreachable."""


# --------------------------------------------------------------------------
# RESP client
# --------------------------------------------------------------------------

def enc_cmd(args):
    """Encode a list of latin-1 strings as a RESP multibulk request."""
    out = bytearray()
    out += b"*%d\r\n" % len(args)
    for a in args:
        b = a.encode("latin-1")
        out += b"$%d\r\n" % len(b)
        out += b
        out += b"\r\n"
    return bytes(out)


class Client:
    """One TCP connection to the server under test, with a RESP parser."""

    def __init__(self, host, port, timeout):
        self.timeout = timeout
        self.buf = bytearray()
        self.eof = False
        self.sock = socket.create_connection((host, port), timeout=timeout)
        self.sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)

    def close(self):
        try:
            self.sock.close()
        except OSError:
            pass

    # -- raw io ------------------------------------------------------------

    def send(self, data):
        try:
            self.sock.sendall(data)
        except OSError as exc:
            raise CaseFailure("write failed: %s" % exc)

    def _fill(self, deadline):
        """Pull at least one more byte into the buffer, or record EOF."""
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise CaseFailure("timed out waiting for data from the server")
        self.sock.settimeout(remaining)
        try:
            chunk = self.sock.recv(65536)
        except socket.timeout:
            raise CaseFailure("timed out waiting for data from the server")
        except OSError as exc:
            if exc.errno in (errno.ECONNRESET, errno.EPIPE):
                self.eof = True
                return
            raise CaseFailure("read failed: %s" % exc)
        if not chunk:
            self.eof = True
            return
        self.buf += chunk

    def _need(self, n, deadline):
        while len(self.buf) < n:
            if self.eof:
                raise CaseFailure(
                    "connection closed by the server mid-reply "
                    "(wanted %d more byte(s), buffer holds %r)"
                    % (n - len(self.buf), bytes(self.buf[:64])))
            self._fill(deadline)

    def _read_line(self, deadline):
        """Read one CRLF-terminated line, returning it without the CRLF."""
        idx = self.buf.find(b"\r\n")
        while idx < 0:
            if self.eof:
                if self.buf:
                    raise CaseFailure(
                        "connection closed inside a reply line: %r"
                        % bytes(self.buf[:64]))
                raise CaseFailure("connection closed by the server")
            self._fill(deadline)
            idx = self.buf.find(b"\r\n")
        line = bytes(self.buf[:idx])
        del self.buf[:idx + 2]
        return line

    # -- resp parsing ------------------------------------------------------

    def read_reply(self, timeout=None):
        deadline = time.monotonic() + (self.timeout if timeout is None else timeout)
        return self._read_reply(deadline)

    def _read_reply(self, deadline):
        line = self._read_line(deadline)
        if not line:
            raise CaseFailure("empty protocol line where a reply was expected")
        kind = line[:1].decode("latin-1")
        payload = line[1:].decode("latin-1")
        if kind == "+":
            return ("+", payload)
        if kind == "-":
            return ("-", payload)
        if kind == ":":
            try:
                return (":", int(payload, 10))
            except ValueError:
                raise CaseFailure("malformed integer reply %r" % payload)
        if kind == "$":
            try:
                n = int(payload, 10)
            except ValueError:
                raise CaseFailure("malformed bulk length %r" % payload)
            if n == -1:
                return ("$", None)
            if n < -1:
                raise CaseFailure("illegal bulk length %d" % n)
            self._need(n + 2, deadline)
            body = bytes(self.buf[:n])
            tail = bytes(self.buf[n:n + 2])
            del self.buf[:n + 2]
            if tail != b"\r\n":
                raise CaseFailure(
                    "bulk string of %d byte(s) not terminated by CRLF (saw %r)"
                    % (n, tail))
            return ("$", body.decode("latin-1"))
        if kind == "*":
            try:
                n = int(payload, 10)
            except ValueError:
                raise CaseFailure("malformed array length %r" % payload)
            if n == -1:
                return ("*", None)
            if n < -1:
                raise CaseFailure("illegal array length %d" % n)
            return ("*", [self._read_reply(deadline) for _ in range(n)])
        raise CaseFailure(
            "unknown reply type byte %r (line %r)" % (kind, line[:64]))

    # -- assertions --------------------------------------------------------

    def expect_closed(self, timeout):
        deadline = time.monotonic() + timeout
        while not self.eof:
            if self.buf:
                raise CaseFailure(
                    "expected the server to close the connection, "
                    "but it sent %r" % bytes(self.buf[:96]))
            self._fill(deadline)
        if self.buf:
            raise CaseFailure(
                "expected the server to close the connection, but it sent %r"
                % bytes(self.buf[:96]))

    def expect_nothing(self, millis):
        deadline = time.monotonic() + millis / 1000.0
        if self.buf:
            raise CaseFailure(
                "expected no data, but %r was already buffered"
                % bytes(self.buf[:96]))
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return
            self.sock.settimeout(remaining)
            try:
                chunk = self.sock.recv(65536)
            except socket.timeout:
                return
            except OSError:
                raise CaseFailure(
                    "expected no data, but the connection errored")
            if not chunk:
                raise CaseFailure(
                    "expected no data, but the server closed the connection")
            self.buf += chunk
            raise CaseFailure(
                "expected no data for %d ms, but the server sent %r"
                % (millis, bytes(self.buf[:96])))


# --------------------------------------------------------------------------
# expectation matching
# --------------------------------------------------------------------------

def describe(reply):
    kind, value = reply
    if kind == "+":
        return "simple string %r" % value
    if kind == "-":
        return "error %r" % value
    if kind == ":":
        return "integer %d" % value
    if kind == "$":
        return "null bulk string" if value is None else "bulk string %r" % value
    if kind == "*":
        if value is None:
            return "null array"
        if not value:
            return "empty array"
        return "array(%d) [%s]" % (len(value),
                                   ", ".join(describe(e) for e in value))
    return repr(reply)


def describe_expect(exp):
    tag, payload = exp[0], exp[1]
    if tag == "+":
        return "simple string %r" % payload
    if tag == "-":
        return "error %r" % payload
    if tag == "-*":
        return "error starting with %r" % payload
    if tag == ":":
        return "integer %d" % payload
    if tag == ":~":
        return "integer in [%d, %d]" % (payload[0], payload[1])
    if tag == "$":
        return "null bulk string" if payload is None else "bulk string %r" % payload
    if tag == "$*":
        return "any non-null bulk string"
    if tag == "*":
        if payload is None:
            return "null array"
        if not payload:
            return "empty array"
        return "array(%d) [%s]" % (
            len(payload), ", ".join(describe_expect(bare(e)) for e in payload))
    if tag == "*u":
        return "array of %d element(s) in any order %r" % (len(payload), payload)
    if tag == "*p":
        return "flat pair array of %d element(s) in any order %r" % (
            len(payload), payload)
    if tag == "*n":
        return "array of exactly %d element(s)" % payload
    if tag == "?":
        return "any reply"
    return repr(exp)


def bare(item):
    """Lift a bare array element into a tagged expectation."""
    if isinstance(item, list):
        return item
    if item is None:
        return ["$", None]
    if isinstance(item, bool):
        raise CaseFailure("booleans are not a RESP2 reply type")
    if isinstance(item, int):
        return [":", item]
    if isinstance(item, str):
        return ["$", item]
    raise CaseFailure("unsupported bare expectation element %r" % (item,))


def comparable(reply):
    """Reduce a scalar reply to a hashable key for multiset comparison."""
    kind, value = reply
    if kind in ("$", ":", "+", "-"):
        return (kind, value)
    raise CaseFailure(
        "unordered comparison needs scalar elements, got %s" % describe(reply))


def comparable_bare(item):
    return comparable(tuple(bare(item)))


def match(exp, reply):
    """Return None when `reply` satisfies `exp`, else an explanation string."""
    if not isinstance(exp, list) or len(exp) != 2:
        raise CaseFailure("malformed expectation %r" % (exp,))
    tag, payload = exp
    kind, value = reply

    if tag == "?":
        return None
    if tag == "+":
        if kind == "+" and value == payload:
            return None
    elif tag == "-":
        if kind == "-" and value == payload:
            return None
    elif tag == "-*":
        if kind == "-" and value.startswith(payload):
            return None
    elif tag == ":":
        if kind == ":" and value == payload:
            return None
    elif tag == ":~":
        if kind == ":" and payload[0] <= value <= payload[1]:
            return None
    elif tag == "$":
        if kind == "$" and value == payload:
            return None
    elif tag == "$*":
        if kind == "$" and value is not None:
            return None
    elif tag == "*n":
        if kind == "*" and value is not None and len(value) == payload:
            return None
    elif tag == "*":
        if payload is None:
            if kind == "*" and value is None:
                return None
        elif kind == "*" and value is not None:
            if len(value) != len(payload):
                return ("array length %d, expected %d"
                        % (len(value), len(payload)))
            for i, (sub_exp, sub_reply) in enumerate(zip(payload, value)):
                why = match(bare(sub_exp), sub_reply)
                if why is not None:
                    return "element %d: %s" % (i, why)
            return None
    elif tag == "*u":
        if kind == "*" and value is not None:
            got = sorted(comparable(e) for e in value)
            want = sorted(comparable_bare(e) for e in payload)
            if got == want:
                return None
            return ("array contents differ as a multiset:\n"
                    "        expected: %r\n"
                    "        actual:   %r" % (want, got))
    elif tag == "*p":
        if len(payload) % 2:
            raise CaseFailure("*p expectation needs an even payload")
        if kind == "*" and value is not None:
            if len(value) % 2:
                return "flat pair array has an odd length %d" % len(value)
            got = sorted((comparable(value[i]), comparable(value[i + 1]))
                         for i in range(0, len(value), 2))
            want = sorted((comparable_bare(payload[i]),
                           comparable_bare(payload[i + 1]))
                          for i in range(0, len(payload), 2))
            if got == want:
                return None
            return ("field/value pairs differ as a multiset:\n"
                    "        expected: %r\n"
                    "        actual:   %r" % (want, got))
    else:
        raise CaseFailure("unknown expectation tag %r" % (tag,))

    return "expected %s\n        actual:   %s" % (describe_expect(exp),
                                                  describe(reply))


