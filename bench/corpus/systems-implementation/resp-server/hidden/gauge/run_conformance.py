def free_port():
    s = socket.socket()
    s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    s.bind(("127.0.0.1", 0))
    port = s.getsockname()[1]
    s.close()
    return port


class Server:
    def __init__(self, run_sh, port, host="127.0.0.1"):
        self.run_sh = Path(run_sh).resolve()
        self.cwd = self.run_sh.parent
        self.host = host
        self.port = port
        self.proc = None
        self.out = None
        self.err = None
        self.restarts = 0

    def start(self):
        if not self.run_sh.exists():
            raise SystemExit("run.sh not found: %s" % self.run_sh)
        if not os.access(str(self.run_sh), os.X_OK):
            raise SystemExit("run.sh is not executable: %s" % self.run_sh)
        self.out = tempfile.TemporaryFile()
        self.err = tempfile.TemporaryFile()
        self.proc = subprocess.Popen(
            [str(self.run_sh), "--port", str(self.port)],
            cwd=str(self.cwd), stdin=subprocess.DEVNULL,
            stdout=self.out, stderr=self.err,
            start_new_session=True)

    def alive(self):
        return self.proc is not None and self.proc.poll() is None

    def wait_ready(self, timeout=READY_TIMEOUT):
        deadline = time.monotonic() + timeout
        last = "no connection attempt made"
        while time.monotonic() < deadline:
            if not self.alive():
                raise ServerGone(
                    "the server exited with status %s before accepting "
                    "connections\n%s" % (self.proc.returncode, self.tail()))
            try:
                sock = socket.create_connection((self.host, self.port), 0.5)
            except OSError as exc:
                last = "connect: %s" % exc
                time.sleep(0.05)
                continue
            try:
                sock.settimeout(2.0)
                sock.sendall(b"PING\r\n")
                data = sock.recv(64)
                if data.startswith(b"+PONG\r\n"):
                    sock.close()
                    return True
                last = "inline PING answered %r, wanted b'+PONG\\r\\n'" % data[:40]
            except OSError as exc:
                last = "inline PING: %s" % exc
            finally:
                sock.close()
            time.sleep(0.05)
        raise ServerGone("the server did not become ready within %.0fs (%s)\n%s"
                         % (timeout, last, self.tail()))

    def tail(self, limit=2048):
        parts = []
        for name, handle in (("stdout", self.out), ("stderr", self.err)):
            if handle is None:
                continue
            try:
                handle.flush()
                handle.seek(0)
                data = handle.read()
            except (OSError, ValueError):
                continue
            if data:
                text = data[-limit:].decode("utf-8", "replace")
                parts.append("--- server %s (last %d bytes) ---\n%s"
                             % (name, min(limit, len(data)), text))
        return "\n".join(parts) if parts else "(the server produced no output)"

    def stop(self):
        if self.proc is None:
            return
        if self.proc.poll() is None:
            try:
                os.killpg(os.getpgid(self.proc.pid), signal.SIGTERM)
            except OSError:
                try:
                    self.proc.terminate()
                except OSError:
                    pass
            deadline = time.monotonic() + SHUTDOWN_GRACE
            while time.monotonic() < deadline and self.proc.poll() is None:
                time.sleep(0.02)
            if self.proc.poll() is None:
                try:
                    os.killpg(os.getpgid(self.proc.pid), signal.SIGKILL)
                except OSError:
                    try:
                        self.proc.kill()
                    except OSError:
                        pass
                try:
                    self.proc.wait(timeout=2)
                except subprocess.TimeoutExpired:
                    pass
        for handle in (self.out, self.err):
            if handle is not None:
                try:
                    handle.close()
                except OSError:
                    pass
        self.out = self.err = None
        self.proc = None

    def restart(self):
        self.stop()
        self.restarts += 1
        self.port = free_port()
        self.start()
        self.wait_ready()


