#!/usr/bin/env python3
"""Conformance runner for the systems-implementation `regex-engine` task.

    python3 run_conformance.py --harness ./run.sh
    python3 run_conformance.py --harness ./run.sh --group classes --group errors
    python3 run_conformance.py --harness ./run.sh --case captures-017 --verbose
    python3 run_conformance.py --list-groups

The runner is language neutral. It starts the solution once as a subprocess,
speaks the line protocol defined in SPEC.md section 3 to it over stdin/stdout,
and compares every reply against the data files in cases/. Nothing about the
solution's language, build system or internal design is visible to it.

Python 3 standard library only. Do not edit this file: it is the grader.

Exit status is 0 if and only if the last line printed is `RESULT PASS`.
"""

from __future__ import annotations

import argparse
import json
import os
import queue
import shlex
import signal
import subprocess
import sys
import threading
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
CASES = HERE / "cases"

DEFAULT_TIME_LIMIT_MS = 2000
STARTUP_TIMEOUT_MS = 20000
SHUTDOWN_GRACE_MS = 5000

OPCODES = {"char", "any", "class", "split", "jmp", "save", "assert", "match"}
ASSERTS = {"bol", "eol", "wordb", "nwordb"}
HEXDIGITS = set("0123456789abcdef")


# --------------------------------------------------------------------- data

def wire_of(case: dict, literal_key: str, build_key: str, default=None):
    """The wire token for a case field, expanded from its build form if needed."""
    if literal_key in case:
        return case[literal_key]
    if build_key in case:
        return "".join(unit * count for unit, count in case[build_key]) or "-"
    return default


def load_groups(names=None) -> list:
    if not CASES.is_dir():
        sys.exit("case directory not found: %s" % CASES)
    groups = []
    for path in sorted(CASES.glob("*/cases.json")):
        with path.open(encoding="utf-8") as fh:
            doc = json.load(fh)
        doc["path"] = path
        groups.append(doc)
    if names:
        wanted = set(names)
        known = {g["group"] for g in groups}
        missing = wanted - known
        if missing:
            sys.exit("unknown group(s): %s\nknown groups: %s"
                     % (", ".join(sorted(missing)), ", ".join(sorted(known))))
        groups = [g for g in groups if g["group"] in wanted]
    return groups


# ------------------------------------------------------------------ harness

class HarnessError(Exception):
    """The harness process died, desynchronised, or ran out of time."""


class Harness:
    """One solution subprocess, spoken to one request at a time."""

    def __init__(self, argv, cwd=None, echo_stderr=True):
        self.argv = argv
        self.cwd = cwd
        self.echo_stderr = echo_stderr
        self.proc = None
        self.lines = None
        self.starts = 0
        self.planned_starts = 0
        self.stderr_tail = []

    # -- lifecycle ------------------------------------------------------
    def start(self, planned=False):
        self.stop()
        self.starts += 1
        if planned:
            self.planned_starts += 1
        self.lines = queue.Queue()
        self.stderr_tail = []
        try:
            self.proc = subprocess.Popen(
                self.argv, cwd=self.cwd,
                stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                stderr=subprocess.PIPE, bufsize=0)
        except OSError as exc:
            sys.exit("cannot start harness %r: %s" % (" ".join(self.argv), exc))
        # The pump threads are bound to the process and queue they were started
        # for: a thread left over from a killed process must never be able to
        # push a stale line, or its end-of-stream marker, into the queue of the
        # harness that replaced it.
        proc, lines = self.proc, self.lines
        threading.Thread(target=self._pump_stdout, args=(proc, lines),
                         daemon=True).start()
        threading.Thread(target=self._pump_stderr, args=(proc,),
                         daemon=True).start()

    @property
    def unplanned_restarts(self) -> int:
        """Restarts that were not part of a case, i.e. real harness failures."""
        return max(0, self.starts - 1 - self.planned_starts)

    def _pump_stdout(self, proc, lines):
        try:
            for raw in iter(proc.stdout.readline, b""):
                lines.put(raw.decode("utf-8", "replace").rstrip("\n"))
        except (ValueError, OSError):
            pass
        lines.put(None)

    def _pump_stderr(self, proc):
        try:
            for raw in iter(proc.stderr.readline, b""):
                text = raw.decode("utf-8", "replace").rstrip("\n")
                self.stderr_tail = (self.stderr_tail + [text])[-20:]
                if self.echo_stderr:
                    sys.stderr.write("[harness] %s\n" % text)
        except (ValueError, OSError):
            pass

    def stop(self):
        if self.proc is None:
            return
        try:
            if self.proc.poll() is None:
                self.proc.kill()
            self.proc.wait(timeout=5)
        except Exception:
            pass
        for stream in (self.proc.stdin, self.proc.stdout, self.proc.stderr):
            try:
                stream.close()
            except Exception:
                pass
        self.proc = None

    def alive(self) -> bool:
        return self.proc is not None and self.proc.poll() is None

    # -- protocol -------------------------------------------------------
    def send(self, line: str):
        if not self.alive():
            raise HarnessError("harness is not running")
        try:
            self.proc.stdin.write((line + "\n").encode("ascii", "strict"))
            self.proc.stdin.flush()
        except (BrokenPipeError, ValueError, UnicodeEncodeError) as exc:
            raise HarnessError("write failed: %s" % exc)

    def read_line(self, deadline: float) -> str:
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise HarnessError("time limit exceeded waiting for a reply")
        try:
            line = self.lines.get(timeout=remaining)
        except queue.Empty:
            raise HarnessError("time limit exceeded waiting for a reply")
        if line is None:
            code = self.proc.poll() if self.proc else None
            raise HarnessError("harness closed stdout (exit status %s)" % code)
        return line

    def close_stdin(self):
        try:
            self.proc.stdin.close()
        except Exception:
            pass

    def wait_exit(self, timeout_s: float):
        try:
            return self.proc.wait(timeout=timeout_s)
        except subprocess.TimeoutExpired:
            return None


# ------------------------------------------------------- expectation checks

def expected_line(case: dict) -> str | None:
    """The single reply line a case expects, when it is a fixed string."""
    exp = case["expect"]
    if "match" in exp:
        spans = exp["match"]
        if spans is None:
            return "NOMATCH"
        flat = " ".join("%d %d" % (s, e) for s, e in spans)
        return "MATCH %d %s" % (len(spans), flat)
    if "find" in exp:
        spans = exp["find"]
        flat = "".join(" %d %d" % (s, e) for s, e in spans)
        return "FIND %d%s" % (len(spans), flat)
    if "error" in exp:
        code, pos = exp["error"]
        return "ERROR %s %d" % (code, pos)
    return None


def parse_count(token: str):
    """A non-negative decimal count exactly as SPEC 3.5 allows it, or None.

    No sign, no leading zeros (`0` itself excepted), digits only.
    """
    if not token.isdigit() or (len(token) > 1 and token[0] == "0"):
        return None
    return int(token)


def check_compile_ok(reply: str, exp: dict) -> str | None:
    parts = reply.split(" ")
    if len(parts) != 2 or parts[0] != "COMPILED":
        return "expected COMPILED <count>"
    n = parse_count(parts[1])
    if n is None:
        return "instruction count %r is not a plain decimal integer" % parts[1]
    if n < 1:
        return "instruction count must be at least 1"
    if "min_instr" in exp and n < exp["min_instr"]:
        return "instruction count %d is below the minimum %d" % (n, exp["min_instr"])
    if "max_instr" in exp and n > exp["max_instr"]:
        return "instruction count %d is above the maximum %d" % (n, exp["max_instr"])
    return None


def parse_program(header: str, body: list) -> tuple:
    """Return (instructions, error). Each instruction is (op, args)."""
    parts = header.split(" ")
    if len(parts) != 2 or parts[0] != "PROGRAM":
        return None, "expected PROGRAM <count>"
    if parse_count(parts[1]) is None:
        return None, "instruction count %r is not a plain decimal integer" % parts[1]
    if parse_count(parts[1]) != len(body):
        return None, "header says %s instruction(s), %d line(s) followed" % (
            parts[1], len(body))
    instrs = []
    for i, line in enumerate(body):
        fields = line.split(" ")
        if len(fields) < 2:
            return None, "instruction %d: %r is not '<pc> <op> [args]'" % (i, line)
        if fields[0] != str(i):
            return None, "instruction %d: program counter is %r, expected %d" % (
                i, fields[0], i)
        op, args = fields[1], fields[2:]
        if op not in OPCODES:
            return None, "instruction %d: unknown opcode %r" % (i, op)
        instrs.append((op, args))
    return instrs, None


def is_hex_cp(token: str) -> bool:
    return (len(token) >= 2 and all(c in HEXDIGITS for c in token)
            and (len(token) == 2 or token[0] != "0")
            and int(token, 16) <= 0x10FFFF)


def check_program(instrs: list, exp: dict) -> str | None:
    n = len(instrs)
    groups = exp.get("groups", 0)
    max_slot = 2 * groups + 1
    ops = [op for op, _ in instrs]

    if n < 1:
        return "program is empty"
    if instrs[0] != ("save", ["0"]):
        return "instruction 0 must be 'save 0', found %r" % (" ".join(
            [instrs[0][0]] + instrs[0][1]))
    if ops.count("match") != 1:
        return "program must contain exactly one 'match' instruction, found %d" % (
            ops.count("match"))

    seen_slots = set()
    classes = []
    for pc, (op, args) in enumerate(instrs):
        if op in ("split", "jmp"):
            want = 2 if op == "split" else 1
            if len(args) != want:
                return "instruction %d: %s takes %d target(s)" % (pc, op, want)
            for t in args:
                if not t.isdigit() or int(t) >= n:
                    return "instruction %d: %s target %r is not a program counter" % (
                        pc, op, t)
        elif op == "save":
            if len(args) != 1 or not args[0].isdigit():
                return "instruction %d: save takes one slot number" % pc
            slot = int(args[0])
            if slot > max_slot:
                return ("instruction %d: save slot %d is out of range for a "
                        "pattern with %d capture group(s)" % (pc, slot, groups))
            seen_slots.add(slot)
        elif op == "char":
            if len(args) != 1 or not is_hex_cp(args[0]):
                return ("instruction %d: char takes one lowercase hex code "
                        "point of at least two digits, found %r" % (pc, args))
        elif op == "assert":
            if len(args) != 1 or args[0] not in ASSERTS:
                return "instruction %d: assert takes one of %s" % (
                    pc, "/".join(sorted(ASSERTS)))
        elif op == "any":
            if args:
                return "instruction %d: any takes no arguments" % pc
        elif op == "match":
            if args:
                return "instruction %d: match takes no arguments" % pc
        elif op == "class":
            if len(args) < 2 or args[0] not in ("p", "n"):
                return ("instruction %d: class takes a polarity (p or n) and at "
                        "least one range" % pc)
            prev_hi = None
            for r in args[1:]:
                if r.count("-") != 1:
                    return "instruction %d: %r is not '<lo>-<hi>'" % (pc, r)
                lo_s, hi_s = r.split("-")
                if not is_hex_cp(lo_s) or not is_hex_cp(hi_s):
                    return ("instruction %d: range %r is not two lowercase hex "
                            "code points" % (pc, r))
                lo, hi = int(lo_s, 16), int(hi_s, 16)
                if lo > hi:
                    return "instruction %d: range %r is inverted" % (pc, r)
                if prev_hi is not None and lo <= prev_hi + 1:
                    return ("instruction %d: ranges must be sorted, disjoint and "
                            "merged; %r follows %04x" % (pc, r, prev_hi))
                prev_hi = hi
            classes.append(" ".join(args))
    for slot in (0, 1):
        if slot not in seen_slots:
            return "program never writes save slot %d" % slot

    if "min_instr" in exp and n < exp["min_instr"]:
        return "program has %d instructions, fewer than the minimum %d" % (
            n, exp["min_instr"])
    if "max_instr" in exp and n > exp["max_instr"]:
        return "program has %d instructions, more than the maximum %d" % (
            n, exp["max_instr"])
    for op in exp.get("require_ops", []):
        if op not in ops:
            return "program contains no %r instruction" % op
    for op in exp.get("forbid_ops", []):
        if op in ops:
            return "program must not contain a %r instruction" % op
    for op, want in (exp.get("count_ops") or {}).items():
        got = ops.count(op)
        if got != want:
            return "program has %d %r instruction(s), expected %d" % (got, op, want)
    chars = [a[0] for op, a in instrs if op == "char"]
    for want in exp.get("require_char", []):
        if want not in chars:
            return "program contains no 'char %s' instruction" % want
    for want in exp.get("require_class", []):
        if want not in classes:
            return "program contains no 'class %s' instruction (found: %s)" % (
                want, "; ".join(classes) or "none")
    asserts = [a[0] for op, a in instrs if op == "assert"]
    for want in exp.get("require_assert", []):
        if want not in asserts:
            return "program contains no 'assert %s' instruction" % want
    return None


# ------------------------------------------------------------------ running

def request_for(case: dict) -> str:
    cmd = case["cmd"]
    pattern = wire_of(case, "pattern", "pattern_build", "-")
    subject = wire_of(case, "subject", "subject_build", "-")
    if cmd == "match":
        return "MATCH %s %s" % (pattern, subject)
    if cmd == "find":
        return "FIND %s %s" % (pattern, subject)
    if cmd == "compile":
        return "COMPILE %s" % pattern
    if cmd == "program":
        return "PROGRAM %s" % pattern
    if cmd == "ping":
        return "PING"
    if cmd == "raw":
        return case["send"]
    raise SystemExit("case %s: unknown cmd %r" % (case["id"], cmd))


def run_case(harness: Harness, case: dict, limit_ms: int) -> tuple:
    """Return (ok, detail, elapsed_ms, request, reply_lines)."""
    cmd = case["cmd"]
    exp = case["expect"]

    if cmd == "eof-exit":
        started = time.monotonic()
        harness.close_stdin()
        code = harness.wait_exit(limit_ms / 1000.0)
        elapsed = (time.monotonic() - started) * 1000.0
        harness.start(planned=True)
        wait_ready(harness, STARTUP_TIMEOUT_MS)
        if code is None:
            return (False, "harness did not exit within %d ms of stdin closing"
                    % limit_ms, elapsed, "<close stdin>", [])
        if code != exp.get("exit_code", 0):
            return (False, "harness exited with status %d, expected %d"
                    % (code, exp.get("exit_code", 0)), elapsed, "<close stdin>", [])
        return True, None, elapsed, "<close stdin>", []

    request = request_for(case)
    want_lines = 1
    if cmd == "raw":
        want_lines = len(exp.get("raw", [""]))

    started = time.monotonic()
    deadline = started + limit_ms / 1000.0
    harness.send(request)
    reply = [harness.read_line(deadline)]
    if cmd == "program" and reply[0].startswith("PROGRAM "):
        count = parse_count(reply[0].split(" ")[1])
        if count is None:
            count = 0
        if count > 200000:
            return (False, "implausible instruction count in %r" % reply[0],
                    (time.monotonic() - started) * 1000.0, request, reply)
        for _ in range(count):
            reply.append(harness.read_line(deadline))
    elif want_lines > 1:
        for _ in range(want_lines - 1):
            reply.append(harness.read_line(deadline))
    elapsed = (time.monotonic() - started) * 1000.0

    for line in reply:
        if any(not (0x20 <= ord(c) <= 0x7E) for c in line):
            return (False, "reply contains non-printable or non-ASCII bytes",
                    elapsed, request, reply)

    if elapsed > limit_ms:
        return (False, "reply took %.0f ms, over the %d ms limit for this case"
                % (elapsed, limit_ms), elapsed, request, reply)

    fixed = expected_line(case)
    if fixed is not None:
        ok = reply[0] == fixed
        return (ok, None if ok else "expected %r, got %r" % (fixed, reply[0]),
                elapsed, request, reply)
    if "raw" in exp:
        ok = reply == exp["raw"]
        return (ok, None if ok else "expected %r, got %r" % (exp["raw"], reply),
                elapsed, request, reply)
    if "compile" in exp:
        detail = check_compile_ok(reply[0], exp)
        return detail is None, detail, elapsed, request, reply
    if "program" in exp:
        instrs, detail = parse_program(reply[0], reply[1:])
        if detail is None:
            detail = check_program(instrs, exp["program"])
        return detail is None, detail, elapsed, request, reply
    if "exit_code" in exp:
        return False, "eof-exit expectation on a non-eof case", elapsed, request, reply
    raise SystemExit("case %s: unrecognised expectation %r" % (case["id"], exp))


def wait_ready(harness: Harness, timeout_ms: int):
    deadline = time.monotonic() + timeout_ms / 1000.0
    harness.send("PING")
    line = harness.read_line(deadline)
    if line != "PONG":
        raise HarnessError("harness answered PING with %r, expected PONG" % line)


def shorten(text: str, width: int = 110) -> str:
    return text if len(text) <= width else text[:width - 3] + "..."


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--harness", default="./run.sh",
                    help="command that speaks the harness protocol (default: ./run.sh)")
    ap.add_argument("--cwd", default=None,
                    help="working directory for the harness (default: this shell's)")
    ap.add_argument("--group", action="append", default=[],
                    help="run only this group; repeatable")
    ap.add_argument("--case", action="append", default=[],
                    help="run only this case id; repeatable")
    ap.add_argument("--list-groups", action="store_true")
    ap.add_argument("--verbose", "-v", action="store_true",
                    help="print every case, not only the failures")
    ap.add_argument("--fail-fast", action="store_true")
    ap.add_argument("--max-restarts", type=int, default=25,
                    help="give up once the harness has had to be restarted this "
                         "many times (default 25); a harness that never replies "
                         "would otherwise burn one time limit per case")
    ap.add_argument("--max-failures", type=int, default=40,
                    help="stop printing failure detail after this many (default 40)")
    ap.add_argument("--time-limit-ms", type=int, default=None,
                    help="override every per-case time limit")
    ap.add_argument("--quiet-stderr", action="store_true",
                    help="do not echo the harness's stderr")
    ap.add_argument("--json", metavar="FILE", help="write a machine-readable report")
    args = ap.parse_args()

    groups = load_groups(args.group)
    if args.list_groups:
        for g in groups:
            print("%-14s %4d  %s" % (g["group"], len(g["cases"]), g["description"]))
        return 0

    wanted_cases = set(args.case)
    selected = []
    for g in groups:
        for case in g["cases"]:
            if wanted_cases and case["id"] not in wanted_cases:
                continue
            selected.append((g, case))
    if wanted_cases:
        found = {c["id"] for _, c in selected}
        for cid in sorted(wanted_cases - found):
            print("unknown case id: %s" % cid, file=sys.stderr)
        if not selected:
            return 2

    argv = shlex.split(args.harness)
    harness = Harness(argv, cwd=args.cwd, echo_stderr=not args.quiet_stderr)
    harness.start()

    print("regex-engine conformance suite")
    print("harness: %s" % args.harness)
    print("groups:  %d   cases: %d" % (
        len({g["group"] for g, _ in selected}), len(selected)))
    print("")

    try:
        wait_ready(harness, STARTUP_TIMEOUT_MS)
    except HarnessError as exc:
        print("HARNESS DID NOT START: %s" % exc)
        print("")
        print("RESULT FAIL")
        harness.stop()
        return 1

    tally = {}
    results = []
    printed = 0
    stop = False
    for g, case in selected:
        name = g["group"]
        tally.setdefault(name, {"cases": 0, "pass": 0, "fail": 0})
        tally[name]["cases"] += 1
        limit = args.time_limit_ms or case.get(
            "time_limit_ms", g.get("default_time_limit_ms", DEFAULT_TIME_LIMIT_MS))
        try:
            ok, detail, elapsed, request, reply = run_case(harness, case, limit)
        except HarnessError as exc:
            ok, detail, elapsed, request, reply = False, str(exc), limit, \
                request_for(case) if case["cmd"] != "eof-exit" else "<close stdin>", []
            if harness.starts > args.max_restarts:
                print("ABORTED: the harness has been restarted %d times; "
                      "the remaining cases were not run"
                      % harness.unplanned_restarts)
                stop = True
            else:
                harness.start()
                try:
                    wait_ready(harness, STARTUP_TIMEOUT_MS)
                except HarnessError as exc2:
                    print("HARNESS COULD NOT BE RESTARTED: %s" % exc2)
                    stop = True
        tally[name][("pass" if ok else "fail")] += 1
        results.append({"group": name, "id": case["id"], "pass": ok,
                        "elapsed_ms": round(elapsed, 1), "detail": detail})
        if args.verbose:
            print("%s %s/%s  %s" % ("PASS" if ok else "FAIL", name, case["id"],
                                    shorten(request)))
            if reply:
                print("     reply: %s" % shorten(" | ".join(reply)))
            if detail:
                print("     %s" % detail)
        elif not ok:
            printed += 1
            if printed <= args.max_failures:
                print("FAIL %s/%s  %s" % (name, case["id"], shorten(request)))
                print("     %s" % (detail or "unexpected reply"))
                if case.get("note"):
                    print("     note: %s" % case["note"])
            elif printed == args.max_failures + 1:
                print("... further failure detail suppressed "
                      "(raise it with --max-failures)")
        if stop or (args.fail_fast and not ok):
            break

    harness.stop()

    total_cases = sum(t["cases"] for t in tally.values())
    total_pass = sum(t["pass"] for t in tally.values())
    total_fail = sum(t["fail"] for t in tally.values())
    rate = (100.0 * total_pass / total_cases) if total_cases else 0.0

    print("")
    print("%-16s %6s %6s %6s" % ("GROUP", "CASES", "PASS", "FAIL"))
    for name in sorted(tally):
        t = tally[name]
        print("%-16s %6d %6d %6d" % (name, t["cases"], t["pass"], t["fail"]))
    print("%-16s %6d %6d %6d" % ("TOTAL", total_cases, total_pass, total_fail))
    print("PASS RATE %.2f%%" % rate)
    if harness.unplanned_restarts:
        print("HARNESS RESTARTS %d" % harness.unplanned_restarts)
    verdict = "PASS" if (total_fail == 0 and total_cases > 0 and not stop) else "FAIL"
    print("RESULT %s" % verdict)

    if args.json:
        with open(args.json, "w", encoding="utf-8") as fh:
            json.dump({"harness": args.harness, "groups": tally,
                       "cases": total_cases, "passed": total_pass,
                       "failed": total_fail, "pass_rate": rate,
                       "harness_restarts": harness.unplanned_restarts,
                       "result": verdict, "results": results}, fh, indent=2)
            fh.write("\n")
    return 0 if verdict == "PASS" else 1


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(130)
