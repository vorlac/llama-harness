#!/usr/bin/env python3
"""Benchmark every installed model across a set of curated presets.

Config-driven: everything lives in ``.data/configs/benchmark.json``, generated by
``scripts/fetch_models.py config``.  The CLI only selects *what* to run, never
*how* - see ``scripts/README.md``.

    scripts/benchmark.py --dry-run          # plan + time estimate, runs nothing
    scripts/benchmark.py                    # every enabled model
    scripts/benchmark.py --model ornith-35b
    scripts/benchmark.py --resume           # skip completed cells
    scripts/benchmark.py --report-only      # rebuild the report from results

How a run is organised
----------------------
For each model, one at a time::

    ensure present (optionally download)
      for each runtime group (a distinct set of load-time flags):
          load the model once
          for each preset sharing that runtime config:
              generate -> score -> record
      perplexity pass
    optionally delete the model before moving on

Runtime flags are grouped because changing one forces a reload; on a 30 GB model
that is ~30 s, and a naive ordering would spend most of the wall clock reloading.

Scoring tiers
-------------
* ``exec``     - the generated code is executed against hidden tests. Objective.
* ``symbols``  - generated docs checked against symbols parsed from the source.
* ``embed``    - retrieval recall@1 on a fixed probe set. Objective.
* ``self-judge`` - the model grades its OWN output. Never mixed into objective
  scores; reported separately and always labelled SELF-GRADED. Its real value is
  *calibration*: self_score vs the objective result shows whether a model can
  tell when it is wrong.
"""

