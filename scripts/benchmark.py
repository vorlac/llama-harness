@dataclass
class InstalledModel:
    id: str
    path: Path
    """Primary .gguf (first shard for sharded models)."""
    manifest: Dict[str, object]
    entry: Optional[catalog.Model]
    mmproj: Optional[Path] = None

    @property
    def category(self) -> str:
        if self.entry:
            return self.entry.category
        return str(self.manifest.get("category") or "general")

    @property
    def quant(self) -> str:
        return str(self.manifest.get("quant") or "?")

    @property
    def size_bytes(self) -> int:
        return int(self.manifest.get("total_bytes") or 0)


def discover_models() -> List[InstalledModel]:
    """Everything under .data/models/ that looks like a usable model.

    Manifest-first (that is the authoritative record), but falls back to a raw
    directory scan so hand-placed weights are still picked up.
    """
    found: List[InstalledModel] = []
    if not MODELS_DIR.is_dir():
        return found

    for model_dir in sorted(p for p in MODELS_DIR.iterdir() if p.is_dir()):
        mid = model_dir.name
        manifest_path = model_dir / ".manifest.json"
        manifest: Dict[str, object] = {}
        if manifest_path.is_file():
            try:
                manifest = json.loads(manifest_path.read_text())
            except (OSError, ValueError):
                manifest = {}

        primary = None
        if manifest.get("primary"):
            cand = model_dir / str(manifest["primary"])
            if cand.is_file():
                primary = cand
        if primary is None:
            weights = [
                p
                for p in sorted(model_dir.rglob("*"))
                if p.suffix.lower() in MODEL_EXTS and "mmproj" not in p.name.lower()
            ]
            # Sharded sets: the first shard is the one llama.cpp is handed.
            if weights:
                primary = weights[0]
        if primary is None:
            continue

        mmproj = None
        if manifest.get("mmproj"):
            cand = model_dir / str(manifest["mmproj"])
            mmproj = cand if cand.is_file() else None
        else:
            projs = [p for p in model_dir.rglob("*") if "mmproj" in p.name.lower()]
            mmproj = projs[0] if projs else None

        found.append(InstalledModel(mid, primary, manifest, catalog.BY_ID.get(mid), mmproj))
    return found


def load_config(path: Optional[Path]) -> Dict[str, object]:
    cfg_path = path or (CONFIGS_DIR / "benchmark.json")
    if not cfg_path.is_file():
        die(
            "no benchmark config at %s\nGenerate one with:\n"
            "  scripts/fetch_models.py config" % cfg_path
        )
    try:
        cfg = json.loads(cfg_path.read_text())
    except ValueError as exc:
        die("benchmark config is not valid JSON: %s" % exc)
    if not isinstance(cfg, dict):
        die("benchmark config must be a JSON object")
    return cfg


def model_config(cfg: Dict[str, object], model_id: str) -> Dict[str, object]:
    for entry in cfg.get("models", []) or []:
        if isinstance(entry, dict) and entry.get("id") == model_id:
            return entry
    return {}


