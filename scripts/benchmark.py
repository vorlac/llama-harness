BENCH_PORT = int(os.environ.get("BENCH_PORT", "8199"))


class ServerSession:
    """One llama-server process holding a model with a fixed runtime config.

    Generation goes through the HTTP API rather than llama-cli for three
    reasons: the response is clean JSON instead of a banner that has to be
    scraped, llama.cpp reports exact per-request timings, and - most
    importantly - the model stays loaded while sampling settings vary. llama-cli
    would reload the whole model for every single run.
    """

    def __init__(
        self, model: InstalledModel, preset: bp.Preset, ctx_size: int, port: int = BENCH_PORT
    ):
        self.model = model
        self.preset = preset
        self.ctx_size = ctx_size
        self.port = port
        self.proc: Optional[subprocess.Popen] = None
        self.base = "http://127.0.0.1:%d" % port
        self.load_seconds = 0.0
        self.log = ""

    def __enter__(self) -> "ServerSession":
        cmd = [
            str(tool("llama-server")),
            "-m",
            str(self.model.path),
            "--host",
            "127.0.0.1",
            "--port",
            str(self.port),
            "--jinja",
        ]
        runtime = dict(self.preset.runtime)
        runtime.setdefault("ctx-size", str(self.ctx_size))
        for key, value in sorted(runtime.items()):
            cmd += ["--%s" % key, value]
        if self.model.mmproj:
            cmd += ["--mmproj", str(self.model.mmproj)]
        self.command = cmd

        logfile = BENCH_DIR / "_server.log"
        logfile.parent.mkdir(parents=True, exist_ok=True)
        self._log_handle = open(logfile, "w")
        started = time.time()
        self.proc = subprocess.Popen(
            cmd,
            stdout=self._log_handle,
            stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL,
        )
        if not self._wait_ready(timeout=900):
            self.close()
            raise RuntimeError("llama-server failed to start; see %s" % logfile)
        self.load_seconds = time.time() - started
        return self

    def _wait_ready(self, timeout: int) -> bool:
        import urllib.request

        deadline = time.time() + timeout
        while time.time() < deadline:
            if self.proc and self.proc.poll() is not None:
                return False
            try:
                with urllib.request.urlopen(self.base + "/health", timeout=3) as resp:
                    if resp.status == 200:
                        return True
            except Exception:
                time.sleep(1)
        return False

    def chat(
        self,
        prompt: str,
        sampling: Dict[str, str],
        max_tokens: int,
        image: Optional[Path] = None,
        timeout: int = 900,
    ) -> Dict[str, object]:
        """One chat completion. Returns {ok, content, reasoning, timings}."""
        import base64
        import urllib.request

        if image:
            data = base64.b64encode(image.read_bytes()).decode()
            content: object = [
                {"type": "text", "text": prompt},
                {"type": "image_url", "image_url": {"url": "data:image/png;base64," + data}},
            ]
        else:
            content = prompt

        payload: Dict[str, object] = {
            "messages": [{"role": "user", "content": content}],
            "max_tokens": max_tokens,
            "stream": False,
        }
        # Map preset sampling keys onto
        # the OpenAI-compatible field names.
        alias = {
            "temp": "temperature",
            "top-p": "top_p",
            "top-k": "top_k",
            "min-p": "min_p",
            "repeat-penalty": "repeat_penalty",
            "seed": "seed",
        }

        for key, value in sampling.items():
            field_name = alias.get(key, key.replace("-", "_"))
            try:
                payload[field_name] = (
                    int(value) if str(value).lstrip("-").isdigit() else float(value)
                )
            except (TypeError, ValueError):
                payload[field_name] = value

        req = urllib.request.Request(
            self.base + "/v1/chat/completions",
            data=json.dumps(payload).encode(),
            headers={"Content-Type": "application/json"},
        )

        started = time.time()
        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                body = json.load(resp)
        except Exception as exc:
            return {
                "ok": False,
                "error": str(exc)[:500],
                "wall_seconds": time.time() - started,
            }

        choice = (body.get("choices") or [{}])[0]
        message = choice.get("message") or {}
        timings = body.get("timings") or {}
        return {
            "ok": True,
            "content": message.get("content") or "",
            "reasoning": message.get("reasoning_content") or "",
            "finish_reason": choice.get("finish_reason"),
            "wall_seconds": time.time() - started,
            "timings": timings,
        }

    def close(self) -> None:
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()
            try:
                self.proc.wait(timeout=30)
            except subprocess.TimeoutExpired:
                self.proc.kill()
        handle = getattr(self, "_log_handle", None)
        if handle:
            handle.close()

    def __exit__(self, *exc) -> None:
        self.close()


def metrics_from_timings(result: Dict[str, object]) -> Dict[str, float]:
    """Normalize llama.cpp's timings block into flat metrics."""
    timings = result.get("timings") or {}
    out: Dict[str, float] = {"wall_seconds": float(result.get("wall_seconds") or 0.0)}
    mapping = {
        "prompt_tokens_per_sec": "prompt_per_second",
        "gen_tokens_per_sec": "predicted_per_second",
        "prompt_ms": "prompt_ms",
        "gen_ms": "predicted_ms",
        "prompt_tokens": "prompt_n",
        "gen_tokens": "predicted_n",
    }
    for out_key, in_key in mapping.items():
        value = timings.get(in_key)
        if isinstance(value, (int, float)):
            out[out_key] = float(value)
    return out


_CODE_BLOCK = re.compile(r"```(?:python)?\s*\n(.*?)```", re.DOTALL | re.IGNORECASE)


def extract_code(text: str) -> Optional[str]:
    blocks = _CODE_BLOCK.findall(text)
    if blocks:
        # Prefer the block that actually defines something.
        for block in blocks:
            if "def " in block or "class " in block:
                return block
        return blocks[0]
    if "def " in text:  # model ignored the formatting instruction
        return text
    return None


def score_exec(output: str, tests: str, timeout: int = 60) -> Dict[str, object]:
    """Execute the model's code against hidden tests in a subprocess.

    Subprocess isolation is deliberate: generated code can hang, exhaust memory
    or call sys.exit, none of which should take the benchmark down with it.
    """
    code = extract_code(output)
    if not code:
        return {
            "kind": "exec",
            "passed": 0,
            "total": 0,
            "ratio": 0.0,
            "error": "no code block in output",
        }

    harness = code + "\n\n" + tests + """

import json as _json, sys as _sys, traceback as _tb
_results = {}
for _name, _fn in sorted(list(globals().items())):
    if _name.startswith("test_") and callable(_fn):
        try:
            _fn()
            _results[_name] = True
        except Exception:
            _results[_name] = False
print("___RESULTS___" + _json.dumps(_results))
"""
    try:
        proc = subprocess.run(
            [sys.executable, "-c", harness],
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        return {
            "kind": "exec",
            "passed": 0,
            "total": 0,
            "ratio": 0.0,
            "error": "tests timed out (likely an infinite loop)",
        }

    marker = "___RESULTS___"
    if marker not in proc.stdout:
        return {
            "kind": "exec",
            "passed": 0,
            "total": 0,
            "ratio": 0.0,
            "error": (proc.stderr or "no results")[-600:],
        }
    try:
        results = json.loads(proc.stdout.split(marker, 1)[1].strip())
    except ValueError:
        return {
            "kind": "exec",
            "passed": 0,
            "total": 0,
            "ratio": 0.0,
            "error": "unparseable results",
        }

    passed = sum(1 for v in results.values() if v)
    total = len(results)
    return {
        "kind": "exec",
        "passed": passed,
        "total": total,
        "ratio": passed / total if total else 0.0,
        "failed_tests": [k for k, v in results.items() if not v],
    }


def score_symbols(output: str, expected: Sequence[str]) -> Dict[str, object]:
    """Objective documentation coverage: did it mention every public symbol?"""
    lowered = output.lower()
    hits = [s for s in expected if s.lower() in lowered]
    missing = [s for s in expected if s.lower() not in lowered]
    return {
        "kind": "symbols",
        "passed": len(hits),
        "total": len(expected),
        "ratio": len(hits) / len(expected) if expected else 0.0,
        "missing": missing,
        "output_chars": len(output),
    }


_SELF_SCORE_RE = re.compile(r"\b(?:score|rating)\b\D{0,12}(\d{1,3})", re.IGNORECASE)


def score_self_judge(
    session: "ServerSession",
    task: bp.Task,
    output: str,
    timeout: int,
    max_tokens: int = 300,
) -> Dict[str, object]:
    """Ask the model to grade its own answer.

    This is NOT an independent quality signal and is never merged into the
    objective score. It is recorded so the report can compute calibration -
    how far the model's self-assessment sits from the measured result.
    """
    if not task.judge_rubric:
        return {"kind": "self-judge", "available": False}

    prompt = (
        "You are grading work that YOU produced. Be critical and look for flaws.\n\n"
        "Question asked:\n%s\n\nAnswer produced:\n%s\n\n"
        "Grading criterion: %s\n\n"
        "Reply with exactly two lines:\n"
        "SCORE: <integer 0-100>\n"
        "FLAWS: <the most serious problem, or 'none'>\n"
        % (task.prompt[:1500], output[:4000], task.judge_rubric)
    )

    reply = session.chat(prompt, {"temp": "0", "seed": "1234"}, max_tokens, timeout=timeout)
    if not reply.get("ok"):
        return {
            "kind": "self-judge",
            "available": False,
            "error": str(reply.get("error"))[:200],
        }

    out = str(reply.get("content") or "")
    match = _SELF_SCORE_RE.search(out)
    score = min(100, int(match.group(1))) if match else None
    flaws = ""

    for line in out.splitlines():
        if line.strip().upper().startswith("FLAWS"):
            flaws = line.split(":", 1)[-1].strip()
            break

    return {
        "kind": "self-judge",
        "available": score is not None,
        "SELF_GRADED": True,
        "note": "Scored by the model on its own output - not independent.",
        "self_score": score,
        "self_reported_flaw": flaws[:400],
    }


def score_embeddings(
    model: InstalledModel,
    timeout: int,
    preset: Optional[bp.Preset] = None,
) -> Dict[str, object]:
    """Recall@1 on a fixed probe set, using llama-server's /v1/embeddings."""
    import urllib.request
    import urllib.error

    probes = bp.embedding_probe_set()
    server = tool("llama-server")
    port = 8137
    cmd = [
        str(server),
        "-m",
        str(model.path),
        "--embeddings",
        "--host",
        "127.0.0.1",
        "--port",
        str(port),
        "--pooling",
        "mean",
    ]

    # Honour the preset's load-time flags so throughput differences between
    # runtime configs are real rather than an artifact of hardcoded defaults.
    runtime = dict(preset.runtime) if preset else {"n-gpu-layers": "999"}
    runtime.setdefault("ctx-size", "2048")
    for key, value in sorted(runtime.items()):
        cmd += ["--%s" % key, value]

    proc = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        base = "http://127.0.0.1:%d" % port
        deadline = time.time() + 180
        while time.time() < deadline:
            try:
                urllib.request.urlopen(base + "/health", timeout=2).read()
                break
            except Exception:
                if proc.poll() is not None:
                    return {"kind": "embed", "error": "server exited during startup"}
                time.sleep(1)
        else:
            return {"kind": "embed", "error": "server did not become ready"}

        def embed(text: str) -> Optional[List[float]]:
            req = urllib.request.Request(
                base + "/v1/embeddings",
                data=json.dumps({"input": text}).encode(),
                headers={"Content-Type": "application/json"},
            )
            try:
                with urllib.request.urlopen(req, timeout=timeout) as resp:
                    return json.load(resp)["data"][0]["embedding"]
            except Exception:
                return None

        def cosine(a, b):
            dot = sum(x * y for x, y in zip(a, b))
            na = sum(x * x for x in a) ** 0.5
            nb = sum(x * x for x in b) ** 0.5
            return dot / (na * nb) if na and nb else 0.0

        correct = 0
        for probe in probes:
            qv = embed(str(probe["query"]))
            if qv is None:
                continue
            sims = []
            for doc in probe["docs"]:
                dv = embed(doc)
                sims.append(cosine(qv, dv) if dv else -1.0)
            if sims and sims.index(max(sims)) == probe["correct"]:
                correct += 1
        return {
            "kind": "embed",
            "passed": correct,
            "total": len(probes),
            "ratio": correct / len(probes) if probes else 0.0,
        }
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=20)
        except subprocess.TimeoutExpired:
            proc.kill()


def run_llama_bench(
    model: InstalledModel,
    preset: bp.Preset,
    timeout: int,
) -> Dict[str, object]:
    """Throughput matrix straight from llama-bench, in JSON."""
    cmd = [
        str(tool("llama-bench")),
        "-m",
        str(model.path),
        "-o",
        "json",
        "-p",
        "512",
        "-n",
        "128",
        "-r",
        "2",
    ]
    rt = preset.runtime
    if "flash-attn" in rt:
        cmd += ["-fa", "1" if rt["flash-attn"] in ("on", "1", "true") else "0"]
    if "cache-type-k" in rt:
        cmd += ["-ctk", rt["cache-type-k"], "-ctv", rt.get("cache-type-v", rt["cache-type-k"])]
    if "ubatch-size" in rt:
        cmd += ["-ub", rt["ubatch-size"]]
    if "batch-size" in rt:
        cmd += ["-b", rt["batch-size"]]

    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except (subprocess.TimeoutExpired, OSError) as exc:
        return {"available": False, "error": str(exc)}
    if proc.returncode != 0:
        return {"available": False, "error": (proc.stderr or "")[-800:]}
    try:
        rows = json.loads(proc.stdout)
    except ValueError:
        return {"available": False, "error": "unparseable llama-bench json"}

    out: Dict[str, object] = {"available": True}
    for row in rows if isinstance(rows, list) else []:
        kind = str(row.get("n_prompt", 0)) != "0" and "prompt" or "gen"
        out["%s_tokens_per_sec" % kind] = row.get("avg_ts")
        out["%s_stddev" % kind] = row.get("stddev_ts")
    return out


def run_perplexity(
    model: InstalledModel,
    preset: bp.Preset,
    chunks: int,
    timeout: int,
) -> Dict[str, object]:
    """Objective quality signal: how much did this config damage the model?

    Uses a fixed corpus derived from the repo's own sources so the measurement
    is reproducible without downloading wikitext.
    """
    corpus = BENCH_DIR / "_corpus.txt"
    if not corpus.is_file():
        corpus.parent.mkdir(parents=True, exist_ok=True)
        parts = []
        for src in sorted((REPO_ROOT / "scripts").glob("*.py")):
            parts.append(src.read_text(errors="replace"))
        readme = REPO_ROOT / "scripts" / "README.md"
        if readme.is_file():
            parts.append(readme.read_text(errors="replace"))
        text = "\n\n".join(parts)
        corpus.write_text((text * 3)[:400_000])

    cmd = [
        str(tool("llama-perplexity")),
        "-m",
        str(model.path),
        "-f",
        str(corpus),
        "--chunks",
        str(chunks),
        "-ngl",
        "999",
        "-c",
        preset.runtime.get("ctx-size", "2048"),
    ]
    if "cache-type-k" in preset.runtime:
        cmd += [
            "-ctk",
            preset.runtime["cache-type-k"],
            "-ctv",
            preset.runtime.get("cache-type-v", preset.runtime["cache-type-k"]),
        ]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except (subprocess.TimeoutExpired, OSError) as exc:
        return {"available": False, "error": str(exc)}

    match = re.search(r"Final estimate:\s*PPL\s*=\s*([0-9.]+)", proc.stdout + proc.stderr)
    if not match:
        match = re.search(r"\bPPL\s*=\s*([0-9.]+)", proc.stdout + proc.stderr)
    if not match:
        return {"available": False, "error": (proc.stderr or "")[-500:]}
    return {"available": True, "perplexity": float(match.group(1)), "chunks": chunks}


def make_test_image(path: Path) -> Path:
    """Write a deterministic bar-chart PNG using only zlib+struct.

    Generated rather than committed so the vision task has a known ground truth
    (4 bars, heights descending left to right) that the report can check against.
    """
    import struct
    import zlib

    if path.is_file():
        return path
    w, h = 320, 200
    bars = [
        (40, 150, (220, 70, 70)),
        (110, 110, (70, 140, 220)),
        (180, 70, (90, 190, 110)),
        (250, 40, (240, 190, 60)),
    ]

    rows = []
    for y in range(h):
        row = bytearray([255, 255, 255] * w)
        for bx, bh, colour in bars:
            if y >= h - bh:
                for x in range(bx - 25, bx + 25):
                    if 0 <= x < w:
                        row[x * 3 : x * 3 + 3] = bytes(colour)
        rows.append(b"\x00" + bytes(row))

    raw = zlib.compress(b"".join(rows), 9)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    png = (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", raw)
        + chunk(b"IEND", b"")
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)
    return path


def plan_runs(
    models: List[InstalledModel],
    cfg: Dict[str, object],
    only: Optional[List[str]],
) -> List[Tuple[InstalledModel, List[bp.Preset], bp.Task]]:
    plan = []
    for model in models:
        if only and model.id not in only:
            continue
        mcfg = model_config(cfg, model.id)
        if mcfg and not mcfg.get("enabled", True):
            continue
        task = bp.TASKS_BY_CATEGORY.get(model.category)
        if task is None:
            warn("%s: no task defined for category %r - skipping" % (model.id, model.category))
            continue
        names = mcfg.get("presets") or [p.name for p in bp.PRESETS]
        presets = [bp.PRESETS_BY_NAME[n] for n in names if n in bp.PRESETS_BY_NAME]
        if task.scoring in ("embed", "audio"):
            # These paths never sample, so presets differing only in sampling
            # would repeat identical work. Keep one preset per runtime config.
            seen = set()
            deduped = []
            for preset in presets:
                if preset.runtime_key not in seen:
                    seen.add(preset.runtime_key)
                    deduped.append(preset)
            presets = deduped
        if task.needs_image and not model.mmproj:
            warn("%s: vision task needs an mmproj; reinstall with --with-mmproj" % model.id)
            continue
        plan.append((model, presets, task))
    return plan


def group_by_runtime(presets: Sequence[bp.Preset]) -> List[Tuple[str, List[bp.Preset]]]:
    """Presets sharing load-time flags can reuse one loaded model."""
    groups: Dict[str, List[bp.Preset]] = {}
    for preset in presets:
        groups.setdefault(preset.runtime_key, []).append(preset)

    return sorted(groups.items(), key=lambda kv: kv[0])


def run_one(
    session: "ServerSession",
    model: InstalledModel,
    preset: bp.Preset,
    task: bp.Task,
    cfg: Dict[str, object],
    out_dir: Path,
) -> RunResult:
    """One preset against an already-loaded model."""
    run_cfg = cfg.get("run", {}) or {}
    timeout = int(run_cfg.get("timeout_seconds", 900))
    mcfg = model_config(cfg, model.id)
    author = dict(mcfg.get("author_sampling") or (model.entry.sampling if model.entry else {}))
    sampling = bp.resolve_sampling(preset, author)

    result = RunResult(model.id, preset.name, task.id, ok=False)

    image = None
    if task.needs_image:
        image = make_test_image(BENCH_DIR / "_assets" / "barchart.png")

    # Reasoning models spend most of their budget in reasoning_content before
    # emitting a single answer token. Giving them a normal budget produces an
    # empty answer and a bogus 0% - the model is not wrong, it was cut off.
    max_tokens = task.max_tokens
    if model.entry is not None and model.entry.reasoning:
        max_tokens = max(max_tokens, int(run_cfg.get("max_tokens_reasoning", 8000)))

    reply = session.chat(task.prompt, sampling, max_tokens, image, timeout)
    result.metrics = metrics_from_timings(reply)
    result.metrics["model_load_seconds"] = session.load_seconds
    if not reply.get("ok"):
        result.error = str(reply.get("error") or "generation failed")
        return result

    text = str(reply.get("content") or "")
    reasoning = str(reply.get("reasoning") or "")
    result.ok = True
    result.output = text

    if task.scoring == "exec" and task.tests:
        result.score = score_exec(text, task.tests)
    elif task.scoring == "symbols" and task.expect_symbols:
        result.score = score_symbols(text, task.expect_symbols)
    else:
        result.score = {"kind": "none", "note": "no objective scorer for this task"}
    result.score["finish_reason"] = reply.get("finish_reason")
    if reply.get("finish_reason") == "length":
        # Distinguish "the model was wrong" from "the model ran out of budget",
        # otherwise a truncated reasoning trace looks identical to a failure.
        result.score["truncated"] = True
        result.score["truncation_note"] = (
            "Hit the %d-token cap; %s. A 0%% here means the answer never "
            "finished, not that it was wrong."
            % (
                max_tokens,
                (
                    "all output went to reasoning"
                    if reasoning and not text
                    else "the answer was cut off"
                ),
            )
        )

    result.metrics["reasoning_chars"] = float(len(reasoning))
    judge_cfg = run_cfg.get("self_judge", {}) or {}
    if judge_cfg.get("enabled", True):
        # A reasoning model needs headroom here too, or it thinks for the
        # whole budget and never emits the SCORE line.
        judge_tokens = 4000 if (model.entry and model.entry.reasoning) else 400
        result.score["self_judge"] = score_self_judge(
            session,
            task,
            text,
            timeout,
            judge_tokens,
        )

    out_dir.mkdir(parents=True, exist_ok=True)
    if run_cfg.get("keep_outputs", True):
        (out_dir / "output.txt").write_text(text)
        if reasoning:
            (out_dir / "reasoning.txt").write_text(reasoning)

    return result


