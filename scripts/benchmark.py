def render_model_table(model: InstalledModel, rows: Sequence[Dict[str, object]],
                       prog) -> None:
    """Per-model results, shown as soon as that model finishes.

    Printed during the run rather than only in report.md, so a multi-hour sweep
    gives you something to read as it goes instead of a wall of log lines.
    """
    rows = [r for r in rows if r.get("model") == model.id]
    if not rows:
        return

    tbl = ui.table(title="[bold]%s[/bold]  [muted]%s / %s[/muted]"
                         % (model.id, model.quant, model.category))
    tbl.add_column("preset", style="model", overflow="fold")
    tbl.add_column("objective", justify="right")
    tbl.add_column("gen t/s", justify="right")
    tbl.add_column("prompt t/s", justify="right")
    tbl.add_column("ppl", justify="right")
    tbl.add_column("self", justify="right")
    tbl.add_column("calib", justify="right")

    for row in rows:
        score = row.get("score") or {}
        metrics = row.get("metrics") or {}
        ratio = score.get("ratio")
        judge = score.get("self_judge") or {}
        self_score = judge.get("self_score")
        calib = "[muted]-[/muted]"
        if isinstance(ratio, (int, float)) and isinstance(self_score, (int, float)):
            delta = self_score - ratio * 100
            # Near zero means the model can tell when it is wrong.
            style = "ok" if abs(delta) <= 10 else "warn"
            calib = "[%s]%+.0f[/%s]" % (style, delta, style)
        ppl = (row.get("perplexity") or {}).get("perplexity")
        tbl.add_row(
            row.get("preset"),
            ui.ratio_text(ratio, score.get("passed"), score.get("total")),
            ui.num(metrics.get("gen_tokens_per_sec")),
            ui.num(metrics.get("prompt_tokens_per_sec")),
            ui.num(ppl, "%.4f"),
            ui.num(self_score, "%.0f"),
            calib,
        )
    prog.log("")
    # The progress object knows whether it owns a live region; a table must go
    # through it either way or it will be interleaved with the bar.
    prog.show(tbl)


def render_summary(results: Sequence[Dict[str, object]], elapsed: float) -> None:
    """Cross-model leaderboard once everything has run."""
    by_model: Dict[str, List[Dict[str, object]]] = {}
    for row in results:
        by_model.setdefault(str(row.get("model")), []).append(row)
    if not by_model:
        return

    ui.rule("Summary")
    tbl = ui.table(caption="Objective = executed tests / symbol coverage / "
                           "recall@1. 'self' is the model grading its own work "
                           "and is NOT independent.")
    tbl.add_column("model", style="model", overflow="fold")
    tbl.add_column("category")
    tbl.add_column("quant")
    tbl.add_column("runs", justify="right")
    tbl.add_column("objective", justify="right")
    tbl.add_column("best t/s", justify="right")
    tbl.add_column("best ppl", justify="right")

    for mid, rows in sorted(by_model.items()):
        ratios = [(r.get("score") or {}).get("ratio") for r in rows]
        ratios = [x for x in ratios if isinstance(x, (int, float))]
        tps = [(r.get("metrics") or {}).get("gen_tokens_per_sec") for r in rows]
        tps = [x for x in tps if isinstance(x, (int, float))]
        ppls = [(r.get("perplexity") or {}).get("perplexity") for r in rows]
        ppls = [x for x in ppls if isinstance(x, (int, float))]
        tbl.add_row(
            mid, str(rows[0].get("category")), str(rows[0].get("quant")),
            str(len(rows)),
            ui.ratio_text(max(ratios)) if ratios else "[muted]-[/muted]",
            ui.num(max(tps)) if tps else "[muted]-[/muted]",
            ui.num(min(ppls), "%.4f") if ppls else "[muted]-[/muted]",
        )
    ui.show(tbl)
    ui.print()
    ui.print("[muted]finished in %.1f min[/muted]" % (elapsed / 60))


def build_report(session: Dict[str, object]) -> str:
    host = session.get("host", {}) or {}
    specs = host.get("specs", {}) or {}
    lines: List[str] = []
    add = lines.append

    add("# Local model benchmark report")
    add("")
    add("Generated %s" % session.get("finished_at", "?"))
    add("")
    add("## Host")
    add("")
    add("```")

    for line in hostinfo.summarize(host):
        add(line)

    add("```")
    add("")
    add("### Full specifications")
    add("")
    add("| property | value |")
    add("|---|---|")
    for key in sorted(specs):
        add("| `%s` | %s |" % (key, specs[key]))

    add("")

    measured = host.get("measured", {}) or {}
    if measured:
        add("### Measured host throughput")
        add("")
        add("| measurement | value | note |")
        add("|---|--:|---|")
        mem = measured.get("memory", {})
        if mem:
            add(
                "| memory copy (single-thread) | %.1f GB/s | %s |"
                % (
                    mem.get("effective_bandwidth_bytes_per_sec", 0) / 1e9,
                    "NOT peak bandwidth - relative indicator only",
                )
            )

        disk = measured.get("disk", {})
        if disk.get("available"):
            add(
                "| disk sequential read | %.1f GB/s | %s |"
                % (
                    disk.get("bytes_per_sec", 0) / 1e9,
                    "page cache warm" if disk.get("page_cache_warm") else "cold",
                )
            )

        cpu = measured.get("cpu_single_thread", {})
        if cpu:
            add(
                "| cpu single-thread | %.1fM ops/s | python integer loop |"
                % (cpu.get("ops_per_sec", 0) / 1e6)
            )

        add("")

    before = host.get("state_before", {}) or {}
    after = session.get("state_after", {}) or {}
    add("### Machine state (throttling check)")
    add("")
    add("| | before | after |")
    add("|---|---|---|")

    for key in ("power_source", "low_power_mode", "battery"):
        if key in before or key in after:
            add("| %s | %s | %s |" % (key, before.get(key, "-"), after.get(key, "-")))

    tb, ta = before.get("thermal") or {}, after.get("thermal") or {}
    for key in sorted(set(tb) | set(ta)):
        flag = "" if tb.get(key) == ta.get(key) else "  **changed**"
        add("| thermal.%s | %s | %s%s |" % (key, tb.get(key, "-"), ta.get(key, "-"), flag))

    add("")

    if tb != ta:
        add(
            "> Thermal or power state changed during the run - later results may "
            "be throttled relative to earlier ones."
        )
        add("")

    add("## Results")
    add("")
    results = session.get("results", []) or []
    by_model: Dict[str, List[Dict[str, object]]] = {}
    for row in results:
        by_model.setdefault(str(row.get("model")), []).append(row)

    add("### Summary by model")
    add("")
    add("| model | category | quant | presets | best objective | best tok/s |")
    add("|---|---|---|--:|--:|--:|")
    for mid, rows in sorted(by_model.items()):
        ratios = [
            (r.get("score") or {}).get("ratio")
            for r in rows
            if isinstance((r.get("score") or {}).get("ratio"), (int, float))
        ]

        tps = [
            (r.get("metrics") or {}).get("gen_tokens_per_sec")
            for r in rows
            if (r.get("metrics") or {}).get("gen_tokens_per_sec")
        ]

        add(
            "| `%s` | %s | %s | %d | %s | %s |"
            % (
                mid,
                rows[0].get("category", "?"),
                rows[0].get("quant", "?"),
                len(rows),
                "%.0f%%" % (max(ratios) * 100) if ratios else "-",
                "%.1f" % max(tps) if tps else "-",
            )
        )

    add("")
    for mid, rows in sorted(by_model.items()):
        add("### `%s`" % mid)
        add("")
        add(
            "| preset | objective | gen tok/s | prompt tok/s | wall s | SELF-graded | calibration |"
        )
        add("|---|--:|--:|--:|--:|--:|--:|")
        for row in rows:
            score = row.get("score") or {}
            metrics = row.get("metrics") or {}
            ratio = score.get("ratio")
            judge = score.get("self_judge") or {}
            self_score = judge.get("self_score")
            calib = "-"

            if isinstance(ratio, (int, float)) and isinstance(self_score, (int, float)):
                calib = "%+.0f" % (self_score - ratio * 100)
            add(
                "| `%s` | %s | %s | %s | %s | %s | %s |"
                % (
                    row.get("preset"),
                    (
                        "%.0f%% (%s/%s)"
                        % (ratio * 100, score.get("passed"), score.get("total"))
                        if isinstance(ratio, (int, float))
                        else "-"
                    ),
                    (
                        "%.1f" % metrics["gen_tokens_per_sec"]
                        if metrics.get("gen_tokens_per_sec")
                        else "-"
                    ),
                    (
                        "%.1f" % metrics["prompt_tokens_per_sec"]
                        if metrics.get("prompt_tokens_per_sec")
                        else "-"
                    ),
                    "%.1f" % metrics["wall_seconds"] if metrics.get("wall_seconds") else "-",
                    "%d" % self_score if isinstance(self_score, (int, float)) else "-",
                    calib,
                )
            )

        add("")
        ppl = [r for r in rows if (r.get("perplexity") or {}).get("available")]
        if ppl:
            add(
                "Perplexity (lower is better - measures how much each runtime "
                "config degrades the model):"
            )

            add("")
            add("| preset | perplexity |")
            add("|---|--:|")
            for row in ppl:
                add("| `%s` | %.4f |" % (row.get("preset"), row["perplexity"]["perplexity"]))

            add("")

    add("## How to read this")
    add("")
    add(
        "- **objective** - executed unit tests, documentation symbol coverage, or "
        "retrieval recall@1. This is the only trustworthy quality column."
    )
    add(
        "- **SELF-graded** - the model scoring *its own* output. It is NOT an "
        "independent measure and must not be read as one."
    )
    add(
        "- **calibration** - `self_score - objective`. Positive means the model "
        "over-rated itself; near zero means it can tell when it is wrong. This is "
        "arguably more interesting than the self score itself."
    )
    add(
        "- **perplexity** - objective, judge-free measure of quantization and "
        "KV-cache damage."
    )
    add("")

    placeholders = session.get("placeholder_categories") or {}
    if placeholders:
        add("## Categories not benchmarked")
        add("")
        for name, reason in sorted(placeholders.items()):
            add("- **%s** - %s" % (name, reason))
        add("")

    add("## Presets")
    add("")
    for preset in bp.PRESETS:
        add("### `%s`" % preset.name)
        add("")
        add(preset.focus)
        add("")
        add("- runtime: `%s`" % (json.dumps(preset.runtime) if preset.runtime else "default"))
        add(
            "- sampling: `%s`"
            % (
                "<author-recommended>"
                if preset.use_author_sampling
                else json.dumps(preset.sampling)
            )
        )
        add("")
    return "\n".join(lines) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="benchmark.py",
        description=__doc__.split("\n\n")[0],
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="Everything else is configured in .data/configs/benchmark.json",
    )
    parser.add_argument(
        "--model",
        action="append",
        metavar="ID",
        help="restrict to this model (repeatable)",
    )
    parser.add_argument(
        "--config",
        type=Path,
        help="alternate benchmark config",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print the plan and time estimate, run nothing",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="skip cells that already have a result.json",
    )
    parser.add_argument(
        "--report-only",
        action="store_true",
        help="rebuild the report from existing results",
    )
    parser.add_argument(
        "--quick-host",
        action="store_true",
        help="skip host throughput measurement",
    )
    parser.add_argument(
        "--no-build-check",
        action="store_true",
        help="do not verify tools against the submodule first",
    )

    args = parser.parse_args(argv)
    cfg = load_config(args.config)
    BENCH_DIR.mkdir(parents=True, exist_ok=True)

    if args.report_only:
        session_path = BENCH_DIR / "session.json"
        if not session_path.is_file():
            die("no previous session at %s" % session_path)

        session = json.loads(session_path.read_text())
        report = BENCH_DIR / "report.md"
        report.write_text(build_report(session))
        info("wrote %s" % report)
        return 0

    if not args.no_build_check:
        ensure_tools_current()

    models = discover_models()
    if not models:
        die(
            "no models found under %s\nInstall one: scripts/fetch_models.py install <id>"
            % MODELS_DIR
        )

    if args.model:
        # An id that matches nothing would otherwise fall through to the generic
        # "nothing to run" below, which points at the wrong thing entirely. A
        # caller that asked for specific models needs to hear that it did not get
        # them, so a typo cannot look like a benchmark with no work to do.
        installed = {m.id for m in models}
        missing = [mid for mid in args.model if mid not in installed]
        if missing:
            die(
                "--model matched nothing: %s\nInstalled: %s\nInstall one: "
                "scripts/fetch_models.py install <id>"
                % (", ".join(missing), ", ".join(sorted(installed)))
            )

    plan = plan_runs(models, cfg, args.model)
    if not plan:
        die("nothing to run - check 'enabled' flags in the benchmark config")

    total_runs = sum(len(presets) for _m, presets, _t in plan)
    # Rough: generation + self-judge per run, plus one model load per group.
    total_groups = sum(len(group_by_runtime(p)) for _m, p, _t in plan)
    est_min = total_runs * 1.5 + total_groups * 1.0

    ui.rule("Benchmark plan")
    plan_table = ui.table()
    plan_table.add_column("model", style="model", overflow="fold")
    plan_table.add_column("category")
    plan_table.add_column("task")
    plan_table.add_column("size", justify="right")
    plan_table.add_column("presets", justify="right")
    plan_table.add_column("loads", justify="right")
    for model, presets, task in plan:
        groups = group_by_runtime(presets)
        size = model.size_bytes / GB
        plan_table.add_row(
            model.id, model.category, task.id,
            "%.1f GB" % size if size else "-",
            str(len(presets)), str(len(groups)),
        )

    ui.show(plan_table)
    # The estimate is prose, so it is a wrapped note rather than a table caption:
    # rich pads a caption out to the table's full width, which left it trailing
    # whitespace and wrapping back to column zero instead of under its own text.
    ui.print(
        "  [muted]%d runs across %d model(s); rough estimate %.0f-%.0f minutes. "
        "Wall clock is dominated by model loads, so large models push the upper "
        "bound.[/muted]"
        % (total_runs, len(plan), est_min * 0.6, est_min * 2.5),
        wrap=True,
        hang=2,
    )
    hint = ui.dependency_hint()
    if hint:
        ui.note("  " + hint)
    ui.print()

    if args.dry_run:
        info(dim("  dry run - nothing executed"))
        return 0

    # Only now is there work to track. Opening this around the plan table meant a
    # dry run rendered a live "0/56" bar it would never advance.
    with ui.progress(total_runs, "benchmarking") as prog:
        ui.rule("Host profile")
        host = hostinfo.collect(MODELS_DIR, quick=args.quick_host)
        pairs = []
        for line in hostinfo.summarize(host):
            parts = line.split(None, 1)
            pairs.append((parts[0], parts[1]) if len(parts) == 2 else (line, ""))
        ui.key_values("", pairs)
        ui.print()

        run_cfg = cfg.get("run", {}) or {}
        evict_cfg = run_cfg.get("eviction", {}) or {}
        ppl_cfg = run_cfg.get("perplexity", {}) or {}

        results: List[Dict[str, object]] = []
        started = time.time()

        for model, presets, task in plan:
            prog.update("%s" % model.id)
            prog.log("")
            prog.log("[bold]== %s[/bold] [muted](%s, %s)[/muted]"
                     % (model.id, model.quant, task.id))
            model_started = len(results)
            mcfg = model_config(cfg, model.id)
            ctx_size = int(mcfg.get("serve_ctx") or 8192)

            for runtime_key, group in group_by_runtime(presets):
                pending = []
                for preset in group:
                    out_dir = BENCH_DIR / model.id / slug(preset.name)
                    if args.resume and (out_dir / "result.json").is_file():
                        prog.log("   [muted]cached[/muted]  %s" % preset.name)
                        prog.advance()
                        results.append(json.loads((out_dir / "result.json").read_text()))
                        continue

                    pending.append((preset, out_dir))

                if not pending:
                    continue

                # Embedding models are scored through their own server helper.
                if task.scoring == "embed":
                    for preset, out_dir in pending:
                        prog.update("%s / %s" % (model.id, preset.name))
                        score = score_embeddings(
                            model,
                            int(run_cfg.get("timeout_seconds", 900)),
                            preset,
                        )
                        row = {
                            "model": model.id,
                            "category": model.category,
                            "quant": model.quant,
                            "preset": preset.name,
                            "task": task.id,
                            "runtime": preset.runtime,
                            "metrics": {},
                            "score": score,
                            "ok": "error" not in score,
                        }

                        results.append(row)
                        out_dir.mkdir(parents=True, exist_ok=True)
                        (out_dir / "result.json").write_text(json.dumps(row, indent=2) + "\n")
                        prog.log("   %s  %-18s recall@1 %s/%s"
                                 % (ui.status_text(bool(row["ok"])), preset.name,
                                    score.get("passed"), score.get("total")))
                        prog.advance()
                    continue

                if task.scoring == "audio":
                    for preset, out_dir in pending:
                        row = {
                            "model": model.id,
                            "category": model.category,
                            "quant": model.quant,
                            "preset": preset.name,
                            "task": task.id,
                            "runtime": preset.runtime,
                            "metrics": {},
                            "ok": False,
                            "score": {
                                "kind": "audio",
                                "available": False,
                                "note": "needs a qwen3tts/OuteTTS model",
                            },
                        }

                        results.append(row)
                        out_dir.mkdir(parents=True, exist_ok=True)
                        (out_dir / "result.json").write_text(json.dumps(row, indent=2) + "\n")

                    continue

                # One model load serves every preset in this runtime group.
                prog.update("%s / loading" % model.id)

                try:
                    with ServerSession(model, pending[0][0], ctx_size) as session:
                        prog.log("   [muted]loaded in %.1fs - %d preset%s share this "
                                 "runtime[/muted]" % (session.load_seconds, len(pending),
                                                      "" if len(pending) == 1 else "s"))
                        for preset, out_dir in pending:
                            prog.update("%s / %s" % (model.id, preset.name))

                            result = run_one(session, model, preset, task, cfg, out_dir)
                            row: Dict[str, object] = {
                                "model": model.id,
                                "category": model.category,
                                "quant": model.quant,
                                "preset": preset.name,
                                "preset_focus": preset.focus,
                                "task": task.id,
                                "runtime": preset.runtime,
                                "metrics": result.metrics,
                                "score": result.score,
                                "ok": result.ok,
                            }

                            if not result.ok:
                                row["error"] = result.error[-600:]
                                prog.log("   %s  %-18s %s"
                                         % (ui.status_text(False), preset.name,
                                            result.error.splitlines()[0][:60]
                                            if result.error else ""))
                            else:
                                ratio = (result.score or {}).get("ratio")
                                tps = result.metrics.get("gen_tokens_per_sec")
                                prog.log("   %s  %-18s %s  %s"
                                         % (ui.status_text(True), preset.name,
                                            ui.ratio_text(ratio),
                                            ("%.1f tok/s" % tps) if tps else ""))

                            results.append(row)
                            prog.advance()
                            out_dir.mkdir(parents=True, exist_ok=True)
                            (out_dir / "result.json").write_text(json.dumps(row, indent=2) + "\n")
                except RuntimeError as exc:
                    warn("%s: %s" % (model.id, exc))
                    continue

                if ppl_cfg.get("enabled", True) and task.scoring in ("exec", "symbols"):
                    # One perplexity pass per runtime group - it depends on the
                    # KV/context config, not on sampling.
                    prog.update("%s / perplexity" % model.id)
                    ppl = run_perplexity(
                        model,
                        pending[0][0],
                        int(ppl_cfg.get("chunks", 24)),
                        int(run_cfg.get("timeout_seconds", 900)),
                    )

                    group_names = {p.name for p, _ in pending}
                    out_dirs = {p.name: d for p, d in pending}
                    for row in results:
                        if row.get("model") == model.id and row.get("preset") in group_names:
                            row["perplexity"] = ppl
                            # Rewrite the on-disk row: it was written before the
                            # perplexity pass, so the file would otherwise lack it
                            # and --resume would replay an incomplete result.
                            target = out_dirs.get(str(row.get("preset")))
                            if target:
                                (target / "result.json").write_text(
                                    json.dumps(row, indent=2) + "\n"
                                )

                    if ppl.get("available"):
                        prog.log("   [muted]perplexity %.4f[/muted]" % ppl["perplexity"])

            render_model_table(model, results[model_started:], prog)

            if evict_cfg.get("delete_after_each"):
                prog.log("   [muted]evicting %s to free disk[/muted]" % model.id)
                evict_model(model)

    session = {
        "started_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(started)),
        "finished_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "duration_seconds": time.time() - started,
        "host": host,
        "state_after": hostinfo.machine_state(),
        "results": results,
        "placeholder_categories": cfg.get("placeholder_categories", {}),
    }

    (BENCH_DIR / "session.json").write_text(json.dumps(session, indent=2, default=str) + "\n")
    report_path = BENCH_DIR / "report.md"
    report_path.write_text(build_report(session))

    render_summary(results, time.time() - started)
    ui.print()
    ui.print("  results  [muted]%s[/muted]" % BENCH_DIR)
    ui.print("  report   [muted]%s[/muted]" % report_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
