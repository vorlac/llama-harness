phase('Composition')
const composition = await agent([
  COMMON, '',
  '## YOUR SCOPE — composition defects across subsystem boundaries (P7)',
  '',
  'Sixteen reviewers have just audited this system, each inside one subsystem or one cross-cutting',
  'sweep. **You hunt what none of them could see: defects that exist only in the seams between',
  'correct components.**',
  '',
  `FIRST read every file in ${PARTS}/ — the ten subsystem audits and the six sweeps. They are your`,
  'map of what each part does and where each reviewer stopped.',
  '',
  'The archetype is C-085 and it is worth understanding before you start. Three rules, each right in',
  'isolation: a blocked dependency is deliberately NOT "stuck" (so conductor_report correctly',
  'refuses) · the dependent is not schedulable (so the gate recommends nothing) · the continuation',
  'engine returns without prompting when nothing is recommended (reasoning soundly that counting a',
  'non-prompt as a futile re-prompt would be a lie). Net effect: a run that CAN NEVER EXIT and CAN',
  'NEVER BE DETECTED — the exact wedge §3.7 exists to end, and the one shape it could not see. No',
  'single-subsystem review would ever have found it.',
  '',
  'Method:',
  '  - For every terminal, exit and escalation path in the system, construct the state where each',
  '    guard says "not mine" and ask who is left holding it. Does the run end with an artifact a',
  '    human receives, or go quiet?',
  '  - For every handoff between two subsystems, ask what each side ASSUMES the other does, and',
  '    whether that assumption is checked anywhere.',
  '  - Look for responsibilities falling between layers: several corrections are exactly "two layers',
  '    each believed the other owned this".',
  '  - Re-read every CROSS-LENS POINTER the sixteen reviewers left that names another SUBSYSTEM —',
  '    those are seam leads they could not follow.',
  '',
  'Reproduce what you find. A composition defect argued but not demonstrated is a suspicion.',
  '',
  '## YOUR OUTPUT',
  '',
  `Write **${PARTS}/composition.md** — skeleton first, then append — same structure as the other`,
  'parts, with ids `COMPOSITION-001`… Return a short summary only.',
].join('\n'), { label: 'composition:P7-seams', phase: 'Composition' })

log(composition ? 'composition pass complete' : 'COMPOSITION PASS RETURNED NOTHING')

phase('Merge')
const merged = await agent([
  COMMON, '',
  '## YOUR SCOPE — assemble one findings document from seventeen parts',
  '',
  `Read EVERY file in ${PARTS}/ in full: ten subsystem audits, six cross-cutting sweeps, and one`,
  'composition pass.',
  '',
  '**This is reconciliation, not concatenation.** A merge that simply appends the parts has failed.',
  '  - **Dedupe.** The same defect will appear in several parts under different framings. Merge them,',
  '    keep the STRONGEST evidence (a reproduction beats a read-verification), note every origin.',
  '  - **Reconcile severity.** Reviewers graded independently and will disagree. Where two parts rate',
  '    the same defect differently, decide and say why. One consistent standard across the register.',
  '  - **Renumber** into a single `ISSUE-NNN` sequence, related issues adjacent. Keep a mapping table',
  '    from each part-local id to its final id — later reviews cite these.',
  '  - **Promote and demote.** An IDEA that is really a defect becomes an ISSUE; an ISSUE that is',
  '    really structural becomes a CROSS-LENS POINTER to the macro review.',
  '  - **Resolve contradictions.** Where two parts disagree on a FACT, go check it yourself and',
  '    record which was right. Do not paper over it.',
  '',
  '## YOUR OUTPUT',
  '',
  `Write **${DIR}/findings-enforcement.md** — the step-2 deliverable — with the structure the`,
  'charter (2-enforcement.md §Output) specifies: executive verdict, the unified ISSUE register, the',
  'IDEA register, CROSS-LENS POINTERS for the macro and capability reviews, the enforcement table,',
  'the merged mutation table, the enumerations, the adversary log, the honesty audit, the coverage',
  'ledger (union of all seventeen, so gaps between reviewers are VISIBLE), and cleared areas.',
  '',
  'Add **MERGE NOTES**: what you deduped, what severities you reconciled and how, what contradictions',
  'you resolved and which side was right, and what the parts did NOT cover between them.',
  '',
  '**MANDATORY COVERAGE ASSERTION — mechanically, not by impression.** The scope assignment in these',
  'workflows was written by hand and is therefore exactly the kind of partition that looks complete',
  'and is not (P1 — one such gap was found and patched in the script before it ever ran). So:',
  '  1. Run `git ls-files` and take every production file under conductor/{core,adapter,plugin,',
  '     tools}/, router/ and scripts/ — excluding conductor/tests/.',
  '  2. Union the coverage ledgers from every part file.',
  '  3. **List every production file appearing in NO ledger**, under "UNOWNED FILES" in MERGE NOTES.',
  'An unowned file is a region this review did not look at. If the list is non-empty, say so at the',
  'TOP of the document, in the executive verdict, so nobody mistakes this review for exhaustive.',
  '',
  `Leave ${PARTS}/ in place — it is the audit trail. Return a short summary: total issues by`,
  'severity, how many were duplicates, and the three most important findings.',
].join('\n'), { label: 'merge:findings-enforcement', phase: 'Merge' })

log(merged ? 'STEP 2 COMPLETE -> docs/reviews/conductor-review/findings-enforcement.md' : 'MERGE RETURNED NOTHING')
